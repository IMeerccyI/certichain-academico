export const certificates: Certificate[] = certificateSeed.map(
  ([id, code, type, studentId, issuerId, status], index) => {
    const student = students.find((item) => item.id === studentId) ?? students[0];
    const issuer = issuers.find((item) => item.id === issuerId) ?? issuers[0];
    const issueDate = `2026-${String(2 + Math.floor(index / 2)).padStart(2, "0")}-${String(8 + index).padStart(2, "0")}T14:15:00.000Z`;
    const revoked = status === "revoked";
    const nftTokenId = id === "certificate-008" ? "NFT-ACAD-0001" : undefined;
    const documentHash = hash(1001 + index);
    const transactionHash = tx(1001 + index);

    return {
      id,
      code,
      type,
      studentId,
      studentName: student.fullName,
      identityDocument: student.identityDocument,
      career: student.career,
      faculty: student.faculty,
      university: student.university,
      issueDate,
      issuerId,
      issuerName: issuer.name,
      issuerRole: issuer.role,
      documentHash,
      blockchainHash: hash(3001 + index),
      transactionHash,
      blockNumber: 7433928 + index * 17,
      status,
      pdfName: `${code.toLowerCase()}.pdf`,
      observations:
        status === "manipulated"
          ? "Caso marcado para demostrar deteccion de documento alterado."
          : "Registro academico precargado para defensa de sistemas distribuidos.",
      receptionSignature:
        status === "pending_reception" ? undefined : `student-reception-${student.id}-${code}`,
      issuerSignature: `issuer-signature-${issuer.id}-${code}`,
      revokedAt: revoked ? `2026-05-${String(12 + index).padStart(2, "0")}T20:15:00.000Z` : undefined,
      revocationReason: revoked ? "Correccion administrativa registrada sin borrar historial." : undefined,
      verificationUrl: `https://certichain.demo.bo/verify/${code}`,
      nftTokenId,
      createdAt: issueDate,
      updatedAt: revoked ? `2026-05-${String(12 + index).padStart(2, "0")}T20:15:00.000Z` : issueDate,
      title: `${certificateTitles[type]} - ${student.career}`,
      kind: type,
      issuedAt: issueDate,
      pdfHash: documentHash,
      txHash: transactionHash,
      signature: `issuer-signature-${issuer.id}-${code}`,
    };
  },
);

